def read_unformatted_binary(filename, gridsize, kind='DP'):
    # Read unformatted binary files created by Fortran
    # For use with surface ejecta and surface dem data files
    if kind == 'DP':
        dt = np.dtype('f8')
    elif kind == 'SP':
        dt = np.dtype('f4')
    elif kind == 'I4B':
        dt = np.dtype('<i4')
    elif kind == 'I8B':
        dt = np.dtypye('<i8')
    data = np.fromfile(filename, dtype=dt)
    data.shape = (gridsize, gridsize)
    
    return data


def read_linked_list_binary(filename, gridsize):
    data = np.empty((gridsize,gridsize),dtype="object")
    with FortranFile(filename, 'r') as f:
        for i in np.arange(gridsize):
            for j in np.arange(gridsize):
                data[j, i] = f.read_reals(np.float64)
    return data


def real2float(realstr):
    """
    Converts a Fortran-generated ASCII string of a real value into a np float type. Handles cases where double precision
    numbers in exponential notation use 'd' or 'D' instead of 'e' or 'E'

    Parameters
    ----------
    realstr : string
        Fortran-generated ASCII string of a real value.

    Returns
    -------
     : float
        The converted floating point value of the input string
    """
    return float(realstr.replace('d', 'E').replace('D', 'E'))

def sed(pattern, replace, source, count=0):
    """Python implementation of unix sed command; not fully functional sed."""

    fin = open(source, 'r')
    num_replaced = 0

    fd, name = mkstemp()
    fout = open(name, 'w')

    for line in fin:
        out = re.sub(pattern, replace, line)
        fout.write(out)

        if out != line:
            num_replaced += 1
        if count and num_replaced > count:
            break

    fout.writelines(fin.readlines())


    fin.close()
    fout.close()

    shutil.move(name, source)
    
    return

def write_datfile(user, filename, seedarr):
    # Write various user and random number seeds into ctem.dat file
    fp = open(filename, 'w')
    
    template = "%(totalimpacts)17d %(ncount)12d %(curyear)19.12E %(restart)s %(fracdone)9.6f %(masstot)19.12E\n"
    fp.write(template % user)
    
    # Write random number seeds to the file
    for index in range(user['seedn']):
        fp.write("%12d\n" % seedarr[index])
    
    fp.close()
    
    return


