# These are directories that are created by CTEM in order to store intermediate results

def create_dir_structure(user, directories):
    """
    Create directories for various output files if they do not already exist
    """

    for dirname in directories:
        dirpath = os.path.join(user['workingdir'], dirname)
        if not os.path.isdir(dirpath):
            print(f"Creating directory {dirpath}")
            os.makedirs(dirpath)
    
    return

def destroy_dir_structure(user, directories):
    """
    Deletes directories generated by create_dir_structure
    """
    for dirname in directories:
        dirpath = os.path.join(user['workingdir'], dirname)
        if os.path.isdir(dirpath):
            print(f"Deleting directory {dirpath}")
            shutil.rmtree(dirpath, ignore_errors=True)

    return

def image_dem(user, DEM):
    dpi = 300.0  # 72.0
    pix = user['pix']
    gridsize = user['gridsize']
    ve = 1.0
    azimuth = 300.0  # user['azimuth']
    solar_angle = 20.0  # user['solar_angle']
    
    ls = LightSource(azdeg=azimuth, altdeg=solar_angle)
    dem_img = ls.hillshade(np.flip(DEM, axis=0), vert_exag=ve, dx=pix, dy=pix)
    
    # Generate image to put into an array
    height = gridsize / dpi
    width = gridsize / dpi
    fig = plt.figure(figsize=(width, height), dpi=dpi)
    ax = plt.axes([0, 0, 1, 1])
    ax.imshow(dem_img, interpolation="nearest", cmap='gray', vmin=0.0, vmax=1.0)
    plt.axis('off')
    # Save image to file
    filename = os.path.join(user['workingdir'],'surf',"surf%06d.png" % user['ncount'])
    plt.savefig(filename, dpi=dpi, bbox_inches=0)
    
    return


def image_regolith(user, regolith):
    # Create scaled regolith image
    minref = user['pix'] * 1.0e-4
    maxreg = np.amax(regolith)
    minreg = np.amin(regolith)
    if (minreg < minref): minreg = minref
    if (maxreg < minref): maxreg = (minref + 1.0e3)
    regolith_scaled = np.copy(regolith)
    np.place(regolith_scaled, regolith_scaled < minref, minref)
    regolith_scaled = 254.0 * (
            (np.log(regolith_scaled) - np.log(minreg)) / (np.log(maxreg) - np.log(minreg)))
    
    # Save image to file
    filename = os.path.join(user['workingdir'],'rego', "rego%06d.png" % user['ncount'])
    height = user['gridsize'] / dpi
    width = height
    fig = plt.figure(figsize=(width, height), dpi=dpi)
    fig.figimage(regolith_scaled, cmap=cm.cividis, origin='lower')
    plt.savefig(filename)
    
    return


def image_shaded_relief(user, DEM):
    dpi = 300.0  # 72.0
    pix = user['pix']
    gridsize = user['gridsize']
    ve = 1.0
    mode = 'overlay'
    azimuth = 300.0  # user['azimuth']
    solar_angle = 20.0  # user['solar_angle']
    
    ls = LightSource(azdeg=azimuth, altdeg=solar_angle)
    cmap = cm.cividis
    
    # If min and max appear to be reversed, then fix them
    if (user['shadedminh'] > user['shadedmaxh']):
        temp = user['shadedminh']
        user['shadedminh'] = user['shadedmaxh']
        user['shadedmaxh'] = temp
    else:
        user['shadedminh'] = user['shadedminh']
        user['shadedmaxh'] = user['shadedmaxh']
    
    # If no shadedmin/max user are read in from ctem.dat, determine the values from the data
    if (user['shadedminhdefault'] == 1):
        shadedminh = np.amin(DEM)
    else:
        shadedminh = user['shadedminh']
    if (user['shadedmaxhdefault'] == 1):
        shadedmaxh = np.amax(DEM)
    else:
        shadedmaxh = user['shadedmaxh']
    
    dem_img = ls.shade(np.flip(DEM, axis=0), cmap=cmap, blend_mode=mode, fraction=1.0,
                       vert_exag=ve, dx=pix, dy=pix,
                       vmin=shadedminh, vmax=shadedmaxh)
    
    # Generate image to put into an array
    height = gridsize / dpi
    width = gridsize / dpi
    fig = plt.figure(figsize=(width, height), dpi=dpi)
    ax = plt.axes([0, 0, 1, 1])
    ax.imshow(dem_img, interpolation="nearest", vmin=0.0, vmax=1.0)
    plt.axis('off')
    # Save image to file
    filename = os.path.join(user['workingdir'],'shaded',"shaded%06d.png" % user['ncount'])
    plt.savefig(filename, dpi=dpi, bbox_inches=0)
    return user


def read_datfile(user, datfile, seedarr):
    # Read and parse ctem.dat file
    
    # Read ctem.dat file
    print('Reading input file ' + datfile)
    fp = open(datfile, 'r')
    lines = fp.readlines()
    fp.close()
    
    # Parse file lines and update parameter fields
    fields = lines[0].split()
    if len(fields) > 0:
        user['totalimpacts'] = real2float(fields[0])
        user['ncount'] = int(fields[1])
        user['curyear'] = real2float(fields[2])
        user['restart'] = fields[3]
        user['fracdone'] = real2float(fields[4])
        user['masstot'] = real2float(fields[5])
    
    # Parse remainder of file to build seed array
    nlines = len(lines)
    index = 1
    while (index < nlines):
        fields = lines[index].split()
        seedarr[index - 1] = real2float(fields[0])
        index += 1
    
    user['seedn'] = index - 1
    
    return


def read_formatted_ascii(filename, skip_lines):
    # Generalized ascii text reader
    # For use with sfdcompare, production, odist, tdist, pdist data files
    try:
        data = np.genfromtxt(filename, skip_header=skip_lines)
    except:
        print(f"Error reading {filename}")
        data = None
    return data


def read_impact_mass(filename):
    # Read impact mass file
    
    fp = open(filename, 'r')
    line = fp.readlines()
    fp.close()
    
    fields = line[0].split()
    if (len(fields) > 0):
        mass = real2float(fields[0])
